// Writes docs/code-map/<area>.md: every source file with what it exports and the first
// sentence of its first doc comment, so people and agents find their way without reading
// the code first. docs/code-map/README.md (how the parts connect) is written by hand.
//   pnpm map            regenerate
//   pnpm map --check    exit 1 if the maps are out of date
//   --quiet             say nothing (the Stop hook in .claude/settings.json runs it after every turn)
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "docs", "code-map");

/** Each map: its title, the source folders it covers, and its test folders. */
const AREAS = [
  { name: "web", title: "Web app (apps/web): Next.js pages, the room IDE, tools", dirs: ["apps/web/app", "apps/web/components", "apps/web/lib", "apps/web/hooks"], tests: ["apps/web/test"] },
  { name: "api", title: "API (apps/api): NestJS REST, auth, realtime, proxies to the runner, AI", dirs: ["apps/api/src"], tests: ["apps/api/test"] },
  { name: "runner", title: "Runner (apps/runner): sandboxes on Docker or Kubernetes, runs, terminals, databases", dirs: ["apps/runner/src"], tests: ["apps/runner/test"] },
  { name: "collab", title: "Collab (apps/collab) and the sandbox agent (sandbox/agent)", dirs: ["apps/collab/src", "sandbox/agent/src"], tests: [] },
  { name: "packages", title: "Shared packages (packages/*): contracts, workspace model, database, auth, emails", dirs: ["packages/contracts/src", "packages/workspace-model/src", "packages/db/src", "packages/auth/src", "packages/emails/src"], tests: [] },
];

const SOURCE = /\.(ts|tsx|mjs)$/;
const SKIP_DIRS = new Set(["node_modules", "dist", ".next", "build", "coverage", "drizzle"]);

function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) => {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) return SKIP_DIRS.has(entry.name) ? [] : walk(path);
      return SOURCE.test(entry.name) && !entry.name.endsWith(".d.ts") ? [path] : [];
    });
}

/**
 * The first sentence of the comment that best says what the file is: one at the top before
 * its imports, else the doc comment of its first exported class, else of its first exported
 * function or component, else its first doc comment.
 */
function summaryOf(text) {
  const docs = [...text.matchAll(/\/\*\*([\s\S]*?)\*\/\s*/g)].map((m) => ({ body: m[1], at: m.index, next: text.slice(m.index + m[0].length, m.index + m[0].length + 60) }));
  const firstImport = text.search(/^import\s/m);
  const pick =
    (firstImport > 0 ? docs.find((doc) => doc.at < firstImport) : undefined) ??
    docs.find((doc) => /^export (default )?(abstract )?class /.test(doc.next)) ??
    docs.find((doc) => /^export (default )?(async )?function/.test(doc.next)) ??
    docs[0];
  const doc = pick?.body;
  if (!doc) return "";
  const prose = doc
    .split("\n")
    .map((line) => line.replace(/^\s*\*\s?/, "").trim())
    .filter((line) => line && !line.startsWith("@"))
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();
  const sentence = /^(.+?[.!?])(?:\s|$)/.exec(prose)?.[1] ?? prose;
  return sentence.length > 220 ? `${sentence.slice(0, 217)}…` : sentence;
}

/** A test file's first comment line, which says what it checks. */
function testSummaryOf(text) {
  const line = /^\/\/ (.+)$/m.exec(text)?.[1] ?? summaryOf(text);
  return line.length > 200 ? `${line.slice(0, 197)}…` : line;
}

function exportsOf(text) {
  const names = [...text.matchAll(/^export (?:default )?(?:declare )?(?:async )?(?:abstract )?(?:function\*?|class|const|let|type|interface|enum) ([A-Za-z0-9_$]+)/gm)].map((m) => m[1]);
  const unique = [...new Set(names)];
  return unique.length > 8 ? [...unique.slice(0, 8), `+${unique.length - 8} more`] : unique;
}

/** A Next.js app-router file's route, from its folders: (groups) dropped, [params] kept. */
function routeOf(rel) {
  const match = /^apps\/web\/app\/(.*?)\/?(page|layout|route|loading|error|not-found)\.(tsx|ts)$/.exec(rel);
  if (!match) return "";
  const path = `/${match[1]}`.replace(/\/\([^)]+\)/g, "").replace(/\/$/, "") || "/";
  return `${match[2]} ${path}`;
}

function mapArea(area) {
  const lines = [
    `# Code map: ${area.title}`,
    "",
    "Generated by `pnpm map` (scripts/code-map.mjs) from each file's exports and the first sentence of its first doc comment. Don't edit it by hand: improve the comment in the file, then run `pnpm map`. How the parts connect: [README.md](README.md).",
    "",
  ];
  for (const dir of area.dirs) {
    const files = walk(join(ROOT, dir)).filter((path) => !/\.test\.tsx?$/.test(path));
    if (!files.length) continue;
    let current = "";
    for (const path of files) {
      const rel = relative(ROOT, path).replaceAll("\\", "/");
      const folder = rel.slice(0, rel.lastIndexOf("/"));
      if (folder !== current) {
        current = folder;
        lines.push("", `## ${folder}`, "");
      }
      const text = readFileSync(path, "utf8");
      const parts = [routeOf(rel), summaryOf(text)].filter(Boolean).join(": ");
      const exported = exportsOf(text);
      lines.push(`- \`${rel.slice(folder.length + 1)}\`${parts ? ` ${parts}` : ""}${exported.length ? ` Exports: ${exported.join(", ")}.` : ""}`);
    }
  }
  const units = area.dirs.flatMap((dir) => walk(join(ROOT, dir))).filter((path) => /\.test\.tsx?$/.test(path));
  const tests = area.tests.flatMap((dir) => walk(join(ROOT, dir)));
  if (units.length || tests.length) {
    lines.push("", "## Tests", "");
    for (const path of tests) lines.push(`- \`${relative(ROOT, path).replaceAll("\\", "/")}\` ${testSummaryOf(readFileSync(path, "utf8"))}`);
    if (units.length) lines.push(`- Unit tests (vitest or node:test, next to the code): ${units.map((path) => `\`${relative(ROOT, path).replaceAll("\\", "/").replace(/^.*\//, "")}\``).join(", ")}.`);
  }
  return `${lines.join("\n").replace(/\n{3,}/g, "\n\n")}\n`;
}

const check = process.argv.includes("--check");
mkdirSync(OUT, { recursive: true });
let stale = 0;
for (const area of AREAS) {
  const file = join(OUT, `${area.name}.md`);
  const next = mapArea(area);
  const now = existsSync(file) ? readFileSync(file, "utf8") : "";
  if (now === next) continue;
  stale++;
  if (!check) writeFileSync(file, next);
}
if (check && stale) {
  console.error(`docs/code-map is out of date (${stale} map${stale === 1 ? "" : "s"}): run pnpm map`);
  process.exit(1);
}
if (!check && !process.argv.includes("--quiet")) console.log(stale ? `docs/code-map: ${stale} map${stale === 1 ? "" : "s"} updated` : "docs/code-map: up to date");
