import { sql } from "drizzle-orm";
import {
  bigint,
  boolean,
  customType,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";

import { organization, user } from "./auth.js";

/** Postgres `bytea` as a Node Buffer (Yjs updates and snapshots). */
export const bytea = customType<{ data: Uint8Array; driverData: Buffer }>({
  dataType: () => "bytea",
  toDriver: (value) => Buffer.from(value),
  fromDriver: (value) => new Uint8Array(value),
});

const timestamps = {
  createdAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp({ withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
};

// Time-ordered ids generated by Postgres 18 itself.
const uuidv7Pk = () => uuid().primaryKey().default(sql`uuidv7()`);

export const roomKind = pgEnum("room_kind", ["workspace", "interview"]);
export const roomVisibility = pgEnum("room_visibility", ["private", "public"]);
export const joinPolicy = pgEnum("join_policy", ["invite", "approval", "open"]);
export const roomRole = pgEnum("room_role", ["owner", "editor", "runner", "viewer", "interviewer", "candidate"]);
/** "removed": the owner removed them or declined their request, and their invite link no longer lets them in. */
export const memberStatus = pgEnum("member_status", ["active", "pending", "removed"]);

export const rooms = pgTable(
  "rooms",
  {
    /** Six-character, human-shareable room code (v1 compatible). */
    id: text().primaryKey(),
    orgId: text()
      .notNull()
      .references(() => organization.id, { onDelete: "cascade" }),
    name: text().notNull(),
    description: text().notNull().default(""),
    kind: roomKind().notNull().default("workspace"),
    visibility: roomVisibility().notNull().default("private"),
    joinPolicy: joinPolicy().notNull().default("invite"),
    templateId: text(),
    settings: jsonb().$type<Record<string, unknown>>().notNull().default({}),
    /** SHA-256 of the invite token; the token itself is never stored. */
    inviteTokenHash: text(),
    createdBy: text().references(() => user.id, { onDelete: "set null" }),
    lastActiveAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
    archivedAt: timestamp({ withTimezone: true }),
    ...timestamps,
  },
  (t) => [
    index().on(t.orgId, t.updatedAt.desc()),
    index("rooms_public_idx").on(t.lastActiveAt.desc()).where(sql`${t.visibility} = 'public'`),
  ],
);

export const roomMembers = pgTable(
  "room_members",
  {
    roomId: text()
      .notNull()
      .references(() => rooms.id, { onDelete: "cascade" }),
    userId: text()
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    role: roomRole().notNull(),
    status: memberStatus().notNull().default("active"),
    invitedBy: text().references(() => user.id, { onDelete: "set null" }),
    ...timestamps,
  },
  (t) => [primaryKey({ columns: [t.roomId, t.userId] }), index().on(t.userId, t.status, t.updatedAt.desc())],
);

/**
 * Append-only Yjs update log. Each row is one locally originated update (or a
 * replica's catch-up diff), timestamped: this is the source for history,
 * time travel and interview replay. See ADR 0005.
 */
export const docUpdates = pgTable(
  "doc_updates",
  {
    docName: text().notNull(),
    seq: bigint({ mode: "number" }).generatedAlwaysAsIdentity(),
    ts: timestamp({ withTimezone: true }).notNull().defaultNow(),
    origin: text().notNull(),
    userId: text(),
    update: bytea().notNull(),
  },
  (t) => [primaryKey({ columns: [t.docName, t.seq] }), index().on(t.docName, t.ts)],
);

/** Compacted state, built from the log (never from a live replica). */
export const docSnapshots = pgTable("doc_snapshots", {
  docName: text().primaryKey(),
  seq: bigint({ mode: "number" }).notNull(),
  state: bytea().notNull(),
  updatedAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
});

