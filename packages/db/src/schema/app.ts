/** Organisation-owned outgoing endpoints; signing secrets are encrypted by the API. */
export const webhooks = pgTable(
  "webhooks",
  {
    id: uuidv7Pk(),
    orgId: text().notNull().references(() => organization.id, { onDelete: "cascade" }),
    url: text().notNull(),
    secretSealed: text().notNull(),
    /** Local E2E fixtures belong to one opted-in dev worker; ordinary workers must not claim them. */
    privateTestOwner: text(),
    events: text().array().notNull(),
    active: boolean().notNull().default(true),
    description: text().notNull().default(""),
    createdBy: text().references(() => user.id, { onDelete: "set null" }),
    ...timestamps,
  },
  (t) => [index().on(t.orgId, t.createdAt.desc())],
);

/** Durable retry queue and receiver-visible history, including every delivery attempt. */
export const webhookDeliveries = pgTable(
  "webhook_deliveries",
  {
    id: uuidv7Pk(),
    webhookId: uuid().notNull().references(() => webhooks.id, { onDelete: "cascade" }),
    event: text().notNull(),
    payload: jsonb().$type<Record<string, unknown>>().notNull(),
    status: text().$type<"pending" | "delivered" | "failed">().notNull().default("pending"),
    attempts: integer().notNull().default(0),
    nextAttemptAt: timestamp({ withTimezone: true }).defaultNow(),
    /** A worker owns this delivery only until its short, recoverable lease expires. */
    lockedBy: text(),
    lockedUntil: timestamp({ withTimezone: true }),
    lastStatusCode: integer(),
    lastError: text(),
    lastResponse: text(),
    attemptLog: jsonb().$type<Array<{
      attempt: number;
      at: string;
      statusCode: number | null;
      error: string | null;
      response: string | null;
      durationMs: number;
    }>>().notNull().default([]),
    // Delivery cursors round-trip through JavaScript Date, which has millisecond precision.
    createdAt: timestamp({ withTimezone: true, precision: 3 }).notNull().defaultNow(),
    deliveredAt: timestamp({ withTimezone: true }),
  },
  (t) => [index().on(t.status, t.nextAttemptAt), index().on(t.webhookId, t.createdAt.desc(), t.id.desc()),
    index("webhook_deliveries_claim_idx").on(t.nextAttemptAt, t.id, t.lockedUntil).where(sql`${t.status} = 'pending'`)],
);

/**
 * A person's editor settings and the VS Code themes they imported, so they follow them to
 * any browser (web: components/room/editor/settings-sync.ts). One row per person.
 */
export const userSettings = pgTable("user_settings", {
  userId: text()
    .primaryKey()
    .references(() => user.id, { onDelete: "cascade" }),
  editor: jsonb().$type<Record<string, unknown>>().notNull().default({}),
  themes: jsonb().$type<unknown[]>().notNull().default([]),
  /** Email a digest of notifications left unread (on unless turned off). */
  emailDigest: boolean().notNull().default(true),
  updatedAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
});

/**
 * A room made from a GitHub repository (api: github/), one row per room. `files` holds the
 * repository's text files as imported, gzipped JSON [{ path, content }]: collab seeds the room's
 * files document from it, and it's the base the room's changes are compared with.
 */
export const roomRepos = pgTable("room_repos", {
  roomId: text()
    .primaryKey()
    .references(() => rooms.id, { onDelete: "cascade" }),
  owner: text().notNull(),
  name: text().notNull(),
  branch: text().notNull(),
  /** The repository's default branch, where pull requests from the room go (null for rooms imported before it was kept). */
  defaultBranch: text(),
  commitSha: text().notNull(),
  files: bytea().notNull(),
  importedBy: text().references(() => user.id, { onDelete: "set null" }),
  importedAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
  /** The secret GitHub signs the room's webhook deliveries with, sealed like tokens; null when activity isn't posted to chat. */
  webhookSecret: text(),
  /** The webhook's id on GitHub when the room made it (so it can remove it); null when it was added by hand. */
  webhookId: bigint({ mode: "number" }),
});

/**
 * A person's GitHub token, for private repositories. Sealed with AES-256-GCM under a key from
 * BETTER_AUTH_SECRET (api: github/token-box.ts); `login` is whose it is, checked when it was saved.
 */
export const githubTokens = pgTable("github_tokens", {
  userId: text()
    .primaryKey()
    .references(() => user.id, { onDelete: "cascade" }),
  login: text().notNull(),
  sealed: text().notNull(),
  updatedAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
});

/**
 * Interview questions, in an organisation's bank. `tests` holds hidden cases too, so
 * these rows never reach a candidate: they get a snapshot's visible part through the API.
 */
export const interviewQuestions = pgTable(
  "interview_questions",
  {
    id: uuidv7Pk(),
    orgId: text()
      .notNull()
      .references(() => organization.id, { onDelete: "cascade" }),
    title: text().notNull(),
    /** Markdown, shown to the candidate. */
    prompt: text().notNull().default(""),
    /** The file the tests run. */
    file: text().notNull(),
    starterFiles: jsonb().$type<Array<{ path: string; content: string }>>().notNull(),
    tests: jsonb().$type<Array<{ id: string; input: string; expected: string; hidden: boolean }>>().notNull().default([]),
    rubric: jsonb().$type<Array<{ id: string; label: string }>>().notNull().default([]),
    durationMinutes: integer().notNull().default(60),
    timeLimitMs: integer().notNull().default(2000),
    createdBy: text().references(() => user.id, { onDelete: "set null" }),
    archivedAt: timestamp({ withTimezone: true }),
    ...timestamps,
  },
  (t) => [index().on(t.orgId, t.updatedAt.desc())],
);

/**
 * One interview: its room, a snapshot of the question (later edits to the bank don't
 * change it), the single-use candidate link, the server's timer and the private
 * scorecard. The room's own edit log (doc_updates) is the source for its replay.
 */
export const interviews = pgTable(
  "interviews",
  {
    id: uuidv7Pk(),
    orgId: text()
      .notNull()
      .references(() => organization.id, { onDelete: "cascade" }),
    roomId: text()
      .notNull()
      .references(() => rooms.id, { onDelete: "cascade" }),
    questionId: uuid().references(() => interviewQuestions.id, { onDelete: "set null" }),
    /** The question as it was when the interview was scheduled, hidden tests and rubric included. */
    question: jsonb()
      .$type<{
        title: string;
        prompt: string;
        file: string;
        starterFiles: Array<{ path: string; content: string }>;
        tests: Array<{ id: string; input: string; expected: string; hidden: boolean }>;
        rubric: Array<{ id: string; label: string }>;
        timeLimitMs: number;
      }>()
      .notNull(),
    candidateName: text().notNull(),
    candidateEmail: text(),
    interviewerId: text().references(() => user.id, { onDelete: "set null" }),
    status: text().$type<"scheduled" | "live" | "finished" | "cancelled">().notNull().default("scheduled"),
    scheduledAt: timestamp({ withTimezone: true }),
    durationMinutes: integer().notNull(),
    startedAt: timestamp({ withTimezone: true }),
    /** When the server closes the interview: the timer browsers count down to. */
    endsAt: timestamp({ withTimezone: true }),
    finishedAt: timestamp({ withTimezone: true }),
    /** SHA-256 of the candidate's link; the token itself is never stored. */
    candidateTokenHash: text().notNull(),
    /** Who used the link. Set once: that's what makes it single-use. */
    candidateUserId: text().references(() => user.id, { onDelete: "set null" }),
    candidateJoinedAt: timestamp({ withTimezone: true }),
    /** Private to interviewers. */
    scorecard: jsonb()
      .$type<{ scores: Array<{ id: string; score: number | null; note: string }>; overall: number | null; recommendation: "yes" | "maybe" | "no" | null; notes: string }>()
      .notNull()
      .default({ scores: [], overall: null, recommendation: null, notes: "" }),
    ...timestamps,
  },
  (t) => [
    index().on(t.orgId, t.createdAt.desc()),
    uniqueIndex().on(t.roomId),
    uniqueIndex().on(t.candidateTokenHash),
    index("interviews_due_idx").on(t.endsAt).where(sql`${t.status} = 'live'`),
  ],
);

/** Each time the tests ran in an interview, with every case's result. Hidden cases' details stay with interviewers. */
export const interviewRuns = pgTable(
  "interview_runs",
  {
    id: uuidv7Pk(),
    interviewId: uuid()
      .notNull()
      .references(() => interviews.id, { onDelete: "cascade" }),
    userId: text().references(() => user.id, { onDelete: "set null" }),
    path: text().notNull(),
    /** Set when the program didn't compile. */
    compileError: text(),
    results: jsonb()
      .$type<Array<{ id: string; hidden: boolean; verdict: string; stdout: string; stderr: string; timeMs: number }>>()
      .notNull()
      .default([]),
    passed: integer().notNull().default(0),
    total: integer().notNull().default(0),
    createdAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index().on(t.interviewId, t.createdAt.desc())],
);
