// Runs after `auth generate`. Better Auth emits `timestamp("col")`, i.e.
// timestamp WITHOUT time zone; every other table uses timestamptz, which
// stores an unambiguous instant. Rewrite in place so regeneration is safe.
import { readFileSync, writeFileSync } from "node:fs";

const file = new URL("../../db/src/schema/auth.ts", import.meta.url);
const source = readFileSync(file, "utf8");
const header = "// GENERATED by `pnpm --filter @codechatter/auth generate-schema`. Do not edit by hand.\n";
const out = header + source.replace(header, "").replace(/timestamp\("([a-z_]+)"\)/g, 'timestamp("$1", { withTimezone: true })');
writeFileSync(file, out);
console.log(`timestamptz: ${(out.match(/withTimezone: true/g) ?? []).length} columns`);
